export function formatStatus(state) {
  if (!state || state.status === 'idle') {
    return 'ℹ️ Сейчас нет активной обработки. Отправьте .txt-файл книги, чтобы начать.';
  }
  switch (state.status) {
    case 'analyzing':
      return '🔎 Идёт анализ структуры книги...';
    case 'processing':
      return `⚙️ Обработка идёт: пакет ${state.currentBatch + 1} из ${state.totalBatches}\nВсего передатчиков: ${state.totalEntries}`;
    case 'done':
      return `✅ Обработка завершена: ${state.totalBatches} файлов отправлено.`;
    case 'cancelled':
      return '🛑 Обработка была отменена. Отправьте .txt-файл, чтобы начать заново.';
    case 'error':
      return `⚠️ Обработка приостановлена из-за ошибки, но будет продолжена автоматически с пакета ${state.currentBatch + 1} из ${state.totalBatches}.\nПоследняя ошибка: ${state.lastError ?? 'неизвестна'}`;
    default:
      return `Статус: ${state.status}`;
  }
}
